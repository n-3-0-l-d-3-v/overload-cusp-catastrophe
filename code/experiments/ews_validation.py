"""
ews_validation.py
=================
E12: can the standard early-warning estimator recover the exponent it is
supposed to recover, on data where the answer is known?

Motivation. Proposition 2 predicts that on approach to the fold the relaxation
rate scales as mu^{1/2} and hence the stationary variance as mu^{-1/2}. The
unit tests confirm this is a true property of the geometry. The empirical
question is different and is rarely asked: does the rolling-window machinery
that the early-warning literature actually uses -- rolling lag-1
autocorrelation and rolling variance over a detrended series -- return those
exponents when applied to a series generated by the model?

This script answers that by simulating from the CHM with known parameters and
comparing three things:

    (a) the exponent computed from the TRUE equilibrium curvature
        (a check that the theory and the code agree)
    (b) the exponent recovered by rolling-window AC1
    (c) the exponent recovered by rolling-window variance

across window lengths, detrending choices and series lengths.

If (b) and (c) do not track (a), then any application of these indicators --
ours included -- is uninterpretable, and a null result obtained with them says
nothing about the underlying dynamics. That has to be established before the
null is reported, not after.

    python experiments/ews_validation.py
"""

from __future__ import annotations

import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
warnings.filterwarnings("ignore")

from chm import potential as P                                  # noqa: E402
from chm import ews as E                                        # noqa: E402
from chm.model import CHMParams, simulate                       # noqa: E402

RESULTS = Path(__file__).resolve().parents[2] / "results"
RESULTS.mkdir(exist_ok=True, parents=True)

SEED = 20260722
WINDOWS = (30, 60, 120)
LENGTHS = (1500, 6000, 20000)
N_REP = 8


def smooth(n, rng, k=40):
    z = rng.standard_normal(n + k)
    s = np.convolve(z, np.ones(k) / k, mode="valid")[:n]
    return (s - s.mean()) / (s.std() + 1e-9)


def _slope(xv, yv):
    m = np.isfinite(xv) & np.isfinite(yv) & (xv > 1e-3) & (yv > 0)
    if m.sum() < 30:
        return np.nan, int(m.sum())
    return float(np.polyfit(np.log(xv[m]), np.log(yv[m]), 1)[0]), int(m.sum())


def main():
    rng = np.random.default_rng(SEED)
    rows = []

    for n in LENGTHS:
        for rep in range(N_REP):
            S, T, U = smooth(n, rng), smooth(n, rng), smooth(n, rng)
            true = CHMParams(beta0=-0.05, beta_S=0.65, beta_T=0.25,
                             beta_U=0.15, alpha0=1.30, alpha_A=0.55,
                             lam=0.18, sigma=0.30, eps=0.03)
            sim = simulate(true, S, T, U, rng=rng)
            x, a, b = sim["x"], sim["a"], sim["b"]
            if not np.all(np.isfinite(x)):
                continue

            mu = P.distance_to_fold(a, b)
            sad = P.saddle(a, b)
            lower = np.where(np.isnan(sad), x < 0, x < sad)

            # (a) ground truth: exponent of the true relaxation rate
            lo, _ = P.stable_equilibria(a, b)
            lam_rel = P.relaxation_rate(lo, a)
            g_true, n_true = _slope(mu, lam_rel)
            rows.append({"n": n, "rep": rep, "estimator": "theory: lambda(mu)",
                         "window": np.nan, "detrend": np.nan,
                         "exponent": g_true, "predicted": 0.5, "n_pts": n_true})

            for win in WINDOWS:
                for detr in (False, True):
                    y = E.detrend(x, win) if detr else x

                    ac1 = E.rolling_ac1(y, win)
                    nl = -np.log(np.clip(ac1, 1e-6, 0.999999))
                    g, npts = _slope(np.where(lower, mu, np.nan),
                                     np.where(lower, nl, np.nan))
                    rows.append({"n": n, "rep": rep,
                                 "estimator": "rolling -logAC1",
                                 "window": win, "detrend": detr,
                                 "exponent": g, "predicted": 0.5,
                                 "n_pts": npts})

                    var = E.rolling_variance(y, win)
                    g, npts = _slope(np.where(lower, mu, np.nan),
                                     np.where(lower, var, np.nan))
                    rows.append({"n": n, "rep": rep,
                                 "estimator": "rolling variance",
                                 "window": win, "detrend": detr,
                                 "exponent": g, "predicted": -0.5,
                                 "n_pts": npts})

        print(f"  n={n} done", flush=True)

    df = pd.DataFrame(rows)
    df.to_csv(RESULTS / "e12_ews_validation_raw.csv", index=False)

    summ = (df.groupby(["estimator", "window", "detrend", "predicted"],
                       dropna=False)["exponent"]
              .agg(["median", "mean", "std", "count"])
              .reset_index())
    summ.to_csv(RESULTS / "e12_ews_validation.csv", index=False)

    print("\n" + "=" * 78)
    print("Can the standard estimator recover the exponent on GROUND-TRUTH data?")
    print("=" * 78)
    print(f"{'estimator':22s} {'win':>4s} {'detr':>5s} {'predicted':>10s} "
          f"{'median':>8s} {'sign ok?':>9s}")
    for _, r in summ.iterrows():
        w = "-" if not np.isfinite(r["window"]) else f"{int(r['window'])}"
        d = "-" if pd.isna(r["detrend"]) else ("yes" if r["detrend"] else "no")
        ok = ("YES" if np.sign(r["median"]) == np.sign(r["predicted"])
              else "NO")
        print(f"{r['estimator']:22s} {w:>4s} {d:>5s} {r['predicted']:>10.2f} "
              f"{r['median']:>8.3f} {ok:>9s}")

    theory = summ[summ["estimator"].str.startswith("theory")]
    rolling = summ[~summ["estimator"].str.startswith("theory")]
    n_wrong_sign = int((np.sign(rolling["median"])
                        != np.sign(rolling["predicted"])).sum())

    print("\nInterpretation")
    print(f"  theory reproduces its own exponent : "
          f"{float(theory['median'].iloc[0]):+.3f} (predicted +0.50)")
    print(f"  rolling-window configurations with the WRONG SIGN: "
          f"{n_wrong_sign} of {len(rolling)}")
    if n_wrong_sign > len(rolling) / 2:
        print("\n  => The rolling-window indicators do NOT recover the predicted")
        print("     exponents on data generated by the model itself. Near the")
        print("     fold the relaxation time exceeds the window, so windowed")
        print("     AC1 saturates towards 1 and -log AC1 towards 0 exactly")
        print("     where the effect is largest; detrending then removes the")
        print("     low-frequency power that carries what remains.")
        print("     Any empirical test of P2 built on these indicators is")
        print("     uninterpretable, and a null obtained from one is not")
        print("     evidence about the dynamics.")


if __name__ == "__main__":
    main()
